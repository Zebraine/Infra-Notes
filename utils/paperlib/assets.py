"""Copy and generate static assets for the paper library."""

from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path

from pygments.formatters import HtmlFormatter

from .config import (
    ASSET_DIR,
    SITE_ASSET_DIR,
    STATIC_DIR,
    VENDOR_ASSET_DIR,
    VENDOR_DIR,
)


def _hash_files(paths: list[Path]) -> str:
    digest = hashlib.sha1()
    for path in sorted(paths):
        if path.is_file():
            digest.update(path.read_bytes())
    return digest.hexdigest()[:10]


def _copy_katex() -> None:
    src = VENDOR_DIR / "katex"
    dst = VENDOR_ASSET_DIR / "katex"
    dst.mkdir(parents=True, exist_ok=True)
    for name in ("katex.min.css", "katex.min.js", "LICENSE"):
        source = src / name
        if source.exists():
            shutil.copy2(source, dst / name)
    if (src / "fonts").exists():
        shutil.copytree(src / "fonts", dst / "fonts", dirs_exist_ok=True)


def _copy_mermaid() -> None:
    src = VENDOR_DIR / "mermaid"
    dst = VENDOR_ASSET_DIR / "mermaid"
    dst.mkdir(parents=True, exist_ok=True)
    for name in ("mermaid.min.js", "LICENSE"):
        source = src / name
        if source.exists():
            shutil.copy2(source, dst / name)


def _write_pygments_css(path: Path) -> None:
    light = HtmlFormatter(style="friendly").get_style_defs(".codehilite")
    dark = HtmlFormatter(style="github-dark").get_style_defs(
        'html[data-theme="dark"] .codehilite'
    )
    path.write_text(
        "/* Generated by Pygments. Do not edit. */\n" + light + "\n\n" + dark + "\n",
        encoding="utf-8",
    )


def prepare_assets() -> dict[str, str]:
    """Rebuild ``papers/assets`` and return an asset manifest/version."""
    ASSET_DIR.mkdir(parents=True, exist_ok=True)

    if SITE_ASSET_DIR.exists():
        shutil.rmtree(SITE_ASSET_DIR)
    SITE_ASSET_DIR.mkdir(parents=True)
    for item in STATIC_DIR.iterdir():
        if item.name.startswith("."):
            continue
        target = SITE_ASSET_DIR / item.name
        if item.is_dir():
            shutil.copytree(item, target)
        else:
            shutil.copy2(item, target)
    _write_pygments_css(SITE_ASSET_DIR / "pygments.css")

    if VENDOR_ASSET_DIR.exists():
        shutil.rmtree(VENDOR_ASSET_DIR)
    VENDOR_ASSET_DIR.mkdir(parents=True)
    _copy_katex()
    _copy_mermaid()

    watched = [
        SITE_ASSET_DIR / "site.css",
        SITE_ASSET_DIR / "site.js",
        SITE_ASSET_DIR / "pygments.css",
        VENDOR_ASSET_DIR / "katex" / "katex.min.css",
        VENDOR_ASSET_DIR / "mermaid" / "mermaid.min.js",
    ]
    version = _hash_files(watched)
    manifest = {
        "version": version,
        "site": "assets/site/",
        "katex": "assets/vendor/katex/",
        "mermaid": "assets/vendor/mermaid/",
    }
    (SITE_ASSET_DIR / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return {"version": version, **manifest}
